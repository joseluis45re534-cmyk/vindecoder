// Generates src/lib/brand-wmis.ts from NHTSA's public vPIC API — the verified,
// per-brand World Manufacturer Identifier (WMI) data shown on /vin-check/[brand].
//
//   node scripts/fetch-brand-wmis.mjs
//
// Method: vPIC files WMIs under the legal MANUFACTURER (e.g. "General Motors"),
// not the brand, so for each parent manufacturer we list its WMIs
// (GetWMIsForManufacturer), keep 3-character passenger-car / MPV / truck codes,
// then confirm each code's MAKE with DecodeWMI and attach it only to the brands
// vPIC itself names. Nothing is hand-typed or guessed.

import fs from 'node:fs';
import path from 'node:path';

const API = 'https://vpic.nhtsa.dot.gov/api/vehicles';
const OUT = path.join(process.cwd(), 'src', 'lib', 'brand-wmis.ts');

// Parent-manufacturer search terms (vPIC does a contains-match on the name).
const MANUFACTURER_QUERIES = [
  'ford motor', 'general motors', 'toyota', 'honda', 'nissan', 'bmw', 'mercedes', 'daimler',
  'audi', 'volkswagen', 'porsche', 'fca', 'chrysler', 'fiat', 'stellantis', 'hyundai', 'kia',
  'subaru', 'fuji heavy', 'mazda', 'tesla', 'volvo', 'jaguar', 'land rover', 'mitsubishi', 'genesis',
];
const KEEP_TYPES = new Set(['Passenger Car', 'Multipurpose Passenger Vehicle (MPV)', 'Truck']);

const brandsSrc = fs.readFileSync(path.join(process.cwd(), 'src', 'lib', 'brands.ts'), 'utf8');
const BRANDS = [...brandsSrc.matchAll(/slug: '([^']+)', name: '([^']+)'/g)].map((m) => ({ slug: m[1], name: m[2] }));
const norm = (s) => String(s || '').toUpperCase().replace(/[^A-Z0-9]/g, '');
const brandByMake = new Map(BRANDS.map((b) => [norm(b.name), b.slug]));

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function getJson(url, tries = 4) {
  for (let i = 0; i < tries; i++) {
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(45000) });
      if (res.ok) return await res.json();
    } catch { /* retry */ }
    await sleep(1500 * (i + 1));
  }
  throw new Error(`vPIC request failed: ${url}`);
}

async function mapLimit(items, limit, fn) {
  const out = new Array(items.length);
  let i = 0;
  await Promise.all(Array.from({ length: limit }, async () => {
    while (i < items.length) {
      const k = i++;
      out[k] = await fn(items[k]);
      await sleep(150);
    }
  }));
  return out;
}

const candidates = new Map(); // wmi -> { country, type }
for (const q of MANUFACTURER_QUERIES) {
  const j = await getJson(`${API}/GetWMIsForManufacturer/${encodeURIComponent(q)}?format=json`);
  for (const r of j.Results || []) {
    const wmi = String(r.WMI || '').toUpperCase();
    if (wmi.length !== 3 || !KEEP_TYPES.has(r.VehicleType)) continue;
    if (!candidates.has(wmi)) candidates.set(wmi, { country: r.Country || '', type: r.VehicleType });
  }
  console.error(`${q}: ${candidates.size} candidate WMIs so far`);
}

const wmis = [...candidates.keys()].sort();
const decoded = await mapLimit(wmis, 4, async (wmi) => {
  const j = await getJson(`${API}/DecodeWMI/${wmi}?format=json`);
  return { wmi, results: j.Results || [] };
});

// vPIC returns every make registered under a WMI as ONE comma-separated string
// (e.g. "DODGE, CHRYSLER, JEEP, RAM"), so split it before matching brands.
const titleMake = (m) => m.toLowerCase().replace(/\b\w/g, (c) => c.toUpperCase()).replace(/^Bmw$/, 'BMW').replace(/^Gmc$/, 'GMC').replace(/^Mini$/, 'MINI').replace(/^Ram$/, 'Ram');
const byBrand = Object.fromEntries(BRANDS.map((b) => [b.slug, []]));
for (const { wmi, results } of decoded) {
  const makes = [...new Set(results.flatMap((r) => String(r.Make || '').split(',')).map((m) => m.trim()).filter(Boolean))];
  const c = candidates.get(wmi);
  for (const make of makes) {
    const slug = brandByMake.get(norm(make));
    if (!slug) continue;
    byBrand[slug].push({
      wmi,
      country: titleCountry(c.country),
      vehicleType: c.type === 'Multipurpose Passenger Vehicle (MPV)' ? 'SUV / MPV' : c.type,
      sharedWith: makes.filter((m) => norm(m) !== norm(make)).map(titleMake),
    });
  }
}

function titleCountry(s) {
  const m = String(s).match(/^(.*?)\s*\((USA)\)$/i);
  if (m) return 'United States';
  return String(s).toLowerCase().replace(/\b\w/g, (c) => c.toUpperCase()).replace(/\bOf\b/g, 'of');
}

const today = new Date().toISOString().slice(0, 10);
// Codes used only by this make first, then shared ones; then by country and code.
const data = Object.fromEntries(Object.entries(byBrand).map(([slug, rows]) => [slug,
  rows.sort((a, b) => (a.sharedWith.length > 0) - (b.sharedWith.length > 0) || a.country.localeCompare(b.country) || a.wmi.localeCompare(b.wmi)),
]));

const ts = `// GENERATED by scripts/fetch-brand-wmis.mjs from NHTSA vPIC on ${today} — do not edit by hand.
// Source: https://vpic.nhtsa.dot.gov/ (GetWMIsForManufacturer + DecodeWMI). Each WMI is listed
// only under the make(s) vPIC itself decodes it to. Re-run the script to refresh.

export const BRAND_WMIS_RETRIEVED = '${today}';

export interface BrandWmi {
  wmi: string;
  country: string;
  vehicleType: string;
  /** Other makes vPIC registers under the same WMI (empty = this make only). */
  sharedWith: string[];
}

export const BRAND_WMIS: Record<string, BrandWmi[]> = ${JSON.stringify(data, null, 2)};
`;
fs.writeFileSync(OUT, ts);
for (const b of BRANDS) { const rows = data[b.slug]; console.error(`${b.slug.padEnd(14)} ${String(rows.length).padStart(3)} WMIs (${rows.filter((r) => !r.sharedWith.length).length} exclusive): ${rows.slice(0, 8).map((r) => r.wmi).join(' ')}`); }
console.error(`wrote ${OUT}`);
